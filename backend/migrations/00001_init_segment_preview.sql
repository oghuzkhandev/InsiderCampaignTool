-- Segment doğrulayıcısı. Go tarafındaki doğrulayıcının (internal/segment)
-- saklanan biçim için aynasıdır: {"all": [{"field","op","value"}, ...]}.
-- İki taraf ayrı koddur; tutarlılık yalnızca entegrasyon testlerindeki senaryolarla
-- doğrulanmıştır. Alan veya operatör eklenince ikisi ve testler birlikte güncellenir.
-- Bu fonksiyonlar PL/pgSQL'dir, çünkü SQL'de AND işleneninin değerlendirme sırası
-- garanti edilmez; IF ile tür kontrolü, tür gerektiren işlemlerden önce yapılır.

-- +goose StatementBegin
CREATE FUNCTION segment_text_valid(v jsonb) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    t text;
BEGIN
    IF jsonb_typeof(v) IS DISTINCT FROM 'string' THEN
        RETURN false;
    END IF;
    t := v #>> '{}';
    -- En az bir boşluk olmayan ASCII karakter (boşluk, tab, satır sonu hariç).
    RETURN t ~ '[^ \t\n\r\f\v]' AND char_length(t) <= 64;
END
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION segment_int_valid(v jsonb, lo numeric, hi numeric) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    n numeric;
BEGIN
    IF jsonb_typeof(v) IS DISTINCT FROM 'number' THEN
        RETURN false;
    END IF;
    n := (v #>> '{}')::numeric;
    RETURN n = trunc(n) AND n >= lo AND n <= hi;
END
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION segment_condition_valid(c jsonb) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    f text;
    o text;
    v jsonb;
BEGIN
    IF jsonb_typeof(c) IS DISTINCT FROM 'object' THEN
        RETURN false;
    END IF;
    IF (SELECT count(*) FROM jsonb_object_keys(c)) <> 3 THEN
        RETURN false;
    END IF;
    IF NOT (c ? 'field' AND c ? 'op' AND c ? 'value') THEN
        RETURN false;
    END IF;
    IF jsonb_typeof(c -> 'field') IS DISTINCT FROM 'string'
       OR jsonb_typeof(c -> 'op') IS DISTINCT FROM 'string' THEN
        RETURN false;
    END IF;

    f := c ->> 'field';
    o := c ->> 'op';
    v := c -> 'value';

    IF f = 'city' THEN
        IF o = 'eq' THEN
            RETURN segment_text_valid(v);
        END IF;
        IF o = 'in' THEN
            IF jsonb_typeof(v) IS DISTINCT FROM 'array' THEN
                RETURN false;
            END IF;
            IF jsonb_array_length(v) < 1 OR jsonb_array_length(v) > 10 THEN
                RETURN false;
            END IF;
            RETURN NOT EXISTS (
                SELECT 1 FROM jsonb_array_elements(v) AS e WHERE NOT segment_text_valid(e)
            );
        END IF;
        RETURN false;
    END IF;

    IF f IN ('last_cart_add_at', 'last_purchase_at') THEN
        IF o IN ('within_last_days', 'not_within_last_days') THEN
            RETURN segment_int_valid(v, 1, 365);
        END IF;
        RETURN false;
    END IF;

    IF f = 'order_count' THEN
        IF o IN ('eq', 'gte', 'lte') THEN
            RETURN segment_int_valid(v, 0, 100000);
        END IF;
        RETURN false;
    END IF;

    RETURN false;
END
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION segment_is_valid(seg jsonb) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF jsonb_typeof(seg) IS DISTINCT FROM 'object' THEN
        RETURN false;
    END IF;
    IF (SELECT count(*) FROM jsonb_object_keys(seg)) <> 1 OR NOT (seg ? 'all') THEN
        RETURN false;
    END IF;
    IF jsonb_typeof(seg -> 'all') IS DISTINCT FROM 'array' THEN
        RETURN false;
    END IF;
    IF jsonb_array_length(seg -> 'all') < 1 OR jsonb_array_length(seg -> 'all') > 10 THEN
        RETURN false;
    END IF;
    RETURN NOT EXISTS (
        SELECT 1 FROM jsonb_array_elements(seg -> 'all') AS c WHERE NOT segment_condition_valid(c)
    );
END
$$;
-- +goose StatementEnd

CREATE TABLE campaigns (
    id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    brief          text        NOT NULL,
    segment        jsonb       NOT NULL,
    status         text        NOT NULL DEFAULT 'draft',
    audience_total integer     NOT NULL,
    audience_sms   integer     NOT NULL,
    audience_email integer     NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT campaigns_brief_valid CHECK (brief ~ '[^ \t\n\r\f\v]' AND char_length(brief) <= 1000),
    CONSTRAINT campaigns_segment_valid CHECK (segment_is_valid(segment)),
    CONSTRAINT campaigns_status_valid CHECK (status IN ('draft', 'approved', 'sending', 'completed')),
    CONSTRAINT campaigns_audience_total_nonneg CHECK (audience_total >= 0),
    CONSTRAINT campaigns_audience_sms_range CHECK (audience_sms >= 0 AND audience_sms <= audience_total),
    CONSTRAINT campaigns_audience_email_range CHECK (audience_email >= 0 AND audience_email <= audience_total)
);

