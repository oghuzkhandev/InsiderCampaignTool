-- +goose Up

-- İçerik sürümleri, onay alanları ve mesaj kuyruğu (CNT-001, ARCHITECTURE §4).
--
-- Bu dosyadaki kısıtlar ve tetikleyiciler ikinci savunma hattıdır: kuralların
-- asıl uygulayıcısı uygulama koddur (internal/content doğrulayıcısı, onay
-- transaction'ındaki FOR UPDATE kilidi ve durum kontrolleri). Veritabanı, kod
-- hatası olsa bile en temel bozulmaları engeller.

-- Temel içerik metni koruması. Go doğrulayıcısının (internal/content) TAM AYNASI
-- DEĞİLDİR; yalnızca şunları zorlar:
--   * metin yalnızca ASCII boşluklarından ibaret değil,
--   * {{first_name}} dışında {{ veya }} yok (bilinmeyen veya yarım değişken yok).
-- Bilerek zorlanmayanlar (yalnızca Go doğrular): SMS 160 ve konu 80 kod noktası
-- sınırı (render sonrası uzunluk alıcı adına bağlıdır), Unicode boşluklardan
-- (ör. NBSP) ibaret metin ve JSON şeması. Hangi girdilerde aynı kararı
-- verdikleri yalnızca entegrasyon testlerindeki senaryo tablosuyla
-- doğrulanmıştır. Değişken kuralı değişirse bu fonksiyon, Go doğrulayıcısı ve
-- test tablosu birlikte güncellenir.
CREATE FUNCTION content_text_valid(t text) RETURNS boolean
LANGUAGE sql IMMUTABLE AS $$
    SELECT t ~ '[^ \t\n\r\f\v]' AND replace(t, '{{first_name}}', '') !~ '\{\{|\}\}'
$$;

-- Yalnızca doğrulanmış sürümler saklanır. Satırlar değişmez (aşağıdaki tetikleyici).
CREATE TABLE campaign_contents (
    campaign_id   uuid        NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    version       integer     NOT NULL,
    source        text        NOT NULL,
    sms_text      text        NOT NULL,
    email_subject text        NOT NULL,
    email_body    text        NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, version),
    CONSTRAINT campaign_contents_version_positive CHECK (version >= 1),
    CONSTRAINT campaign_contents_source_valid CHECK (source IN ('llm', 'human')),
    CONSTRAINT campaign_contents_sms_valid CHECK (content_text_valid(sms_text)),
    -- Konu e-posta başlığına girer; satır sonu başlık enjeksiyonuna açar.
    CONSTRAINT campaign_contents_subject_valid
        CHECK (content_text_valid(email_subject) AND email_subject !~ '[\r\n]'),
    CONSTRAINT campaign_contents_body_valid CHECK (content_text_valid(email_body))
);

-- Onay alanları. Kısıtlar "durum X ise şu alanlar" biçiminde yazıldı; böylece
-- bilinmeyen bir durum için campaigns_status_valid dışında ikinci bir kısıt
-- patlamaz.
ALTER TABLE campaigns
    ADD COLUMN approved_content_version integer,
    ADD COLUMN approved_at              timestamptz,
    ADD COLUMN completed_at             timestamptz,
    -- Onaylanan sürüm bu kampanyaya ait gerçek bir sürümdür (NULL ise denetlenmez).
    ADD CONSTRAINT campaigns_approved_content_fk
        FOREIGN KEY (id, approved_content_version)
        REFERENCES campaign_contents (campaign_id, version),
    ADD CONSTRAINT campaigns_draft_has_no_approval
        CHECK (status <> 'draft' OR (approved_content_version IS NULL
               AND approved_at IS NULL AND completed_at IS NULL)),
    ADD CONSTRAINT campaigns_approved_has_content
        CHECK (status NOT IN ('approved', 'sending', 'completed')
               OR (approved_content_version IS NOT NULL AND approved_at IS NOT NULL)),
    ADD CONSTRAINT campaigns_completed_at_matches
        CHECK ((status = 'completed') = (completed_at IS NOT NULL));

-- Mesaj kuyruğu. Onay transaction'ı alıcı başına `queued` satır yazar; worker
-- (SND-001) claim, retry ve sonuç sütunlarını kullanır. failure_reason değer
-- listesi SND-001'e bırakıldı, bu yüzden kısıtlanmadı. Gönderilecek metin
-- mesaja kopyalanmaz; worker campaigns.approved_content_version üzerinden okur.
CREATE TABLE messages (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id     uuid        NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    user_id         bigint      NOT NULL REFERENCES users (id),
    channel         text        NOT NULL,
    recipient       text        NOT NULL, -- onay anındaki telefon veya e-posta
    status          text        NOT NULL DEFAULT 'queued',
    attempts        integer     NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    claim_token     uuid,
    claimed_at      timestamptz,
    idempotency_key text        NOT NULL,
    last_error      text,
    failure_reason  text,
    sent_at         timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT messages_unique_per_recipient UNIQUE (campaign_id, user_id, channel),
    CONSTRAINT messages_channel_valid CHECK (channel IN ('sms', 'email')),
    CONSTRAINT messages_status_valid
        CHECK (status IN ('queued', 'sending', 'sent', 'failed', 'skipped')),
    CONSTRAINT messages_attempts_nonneg CHECK (attempts >= 0),
    CONSTRAINT messages_recipient_nonblank CHECK (recipient ~ '[^ \t\n\r\f\v]'),
    -- Sabit biçim: campaign:user:channel. Üretilmiş sütun yerine CHECK, uuid
    -- dönüşümünün "immutable" sayılıp sayılmamasına bağlı olmamak için.
    CONSTRAINT messages_idempotency_key_valid
        CHECK (idempotency_key = campaign_id::text || ':' || user_id::text || ':' || channel),
    CONSTRAINT messages_sending_has_claim
        CHECK (status <> 'sending' OR (claim_token IS NOT NULL AND claimed_at IS NOT NULL)),
    CONSTRAINT messages_sent_at_matches CHECK ((status = 'sent') = (sent_at IS NOT NULL))
);

CREATE INDEX messages_claim_idx    ON messages (channel, next_attempt_at) WHERE status = 'queued';
CREATE INDEX messages_reaper_idx   ON messages (claimed_at)               WHERE status = 'sending';
CREATE INDEX messages_campaign_idx ON messages (campaign_id, status);

-- Tetikleyiciler. Uygulama kilidi ve durum kontrolleri (kampanya satırı FOR
-- UPDATE, status = 'draft' kontrolü) yerinde kalır; bunlar kod hatasına karşı
-- veritabanı düzeyindeki korumadır.

-- 1) İçerik sürümü satırları değişmez.
-- +goose StatementBegin
CREATE FUNCTION campaign_contents_block_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'campaign_contents satırları değişmez' USING ERRCODE = 'restrict_violation';
END
$$;
-- +goose StatementEnd

CREATE TRIGGER campaign_contents_no_update
    BEFORE UPDATE ON campaign_contents
    FOR EACH ROW EXECUTE FUNCTION campaign_contents_block_update();

-- 2) Onaylanmış (draft olmayan) kampanyaya yeni sürüm eklenemez.
-- FOR SHARE: eşzamanlı bir onay kampanya satırını kilitlemişse beklenir ve
-- onaydan sonraki durum okunur. Uygulama, sürüm yazarken kampanya satırını
-- zaten FOR UPDATE ile kilitler; bu transaction'da FOR SHARE etkisizdir. Kampanya
-- yoksa satır geçirilir ve yabancı anahtar hatası kendi adıyla döner.
-- +goose StatementBegin
CREATE FUNCTION campaign_contents_require_draft() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    current_status text;
BEGIN
    SELECT status INTO current_status FROM campaigns WHERE id = NEW.campaign_id FOR SHARE;
    IF FOUND AND current_status <> 'draft' THEN
        RAISE EXCEPTION 'onaylanmış kampanyaya içerik sürümü eklenemez' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END
$$;
-- +goose StatementEnd

CREATE TRIGGER campaign_contents_draft_only
    BEFORE INSERT ON campaign_contents
    FOR EACH ROW EXECUTE FUNCTION campaign_contents_require_draft();

-- 3) Onaylanan içerik sürümü sonradan değiştirilemez.
-- +goose StatementBegin
CREATE FUNCTION campaigns_keep_approved_version() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.approved_content_version IS NOT NULL
       AND NEW.approved_content_version IS DISTINCT FROM OLD.approved_content_version THEN
        RAISE EXCEPTION 'onaylanan içerik sürümü değiştirilemez' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END
$$;
-- +goose StatementEnd

CREATE TRIGGER campaigns_approved_version_fixed
    BEFORE UPDATE ON campaigns
    FOR EACH ROW EXECUTE FUNCTION campaigns_keep_approved_version();

-- +goose Down

-- Dikkat: geri alma içerik sürümlerini, onay alanlarını ve mesaj kuyruğunu
-- siler. Draft olmayan (onaylanmış, gönderilen veya tamamlanmış) kampanya
-- varsa bu veri kaybolacağı için hiçbir şey silinmeden reddedilir. Geri almak
-- için önce o kampanyaların bilinçli olarak silinmesi gerekir.
--
-- Koruma Down'un ilk ifadeleridir; hiçbir DROP çalışmadan hata döner. Kontrol
-- ile DROP arasında bir onayın commit edilememesi için tablolar kontrolden
-- ÖNCE kilitlenir: uçuştaki bir onay varsa Down onu bekler, sonra onaylı
-- kampanyayı görüp reddeder. Kilitsiz kontrol, henüz commit edilmemiş onayı
-- görmez ve DROP onay commit olunca çalışıp onay verisini silerdi. Tablolar
-- Down'un sileceği her tabloyu kapsar ve tek ifadede, sabit sırayla kilitlenir.
-- Goose Down'u tek transaction'da çalıştırır; kilitler transaction sonunda
-- (commit veya hata) bırakılır.
LOCK TABLE campaigns, campaign_contents, messages IN ACCESS EXCLUSIVE MODE;

-- +goose StatementBegin
DO $$
DECLARE
    n integer;
BEGIN
    SELECT count(*) INTO n FROM campaigns WHERE status <> 'draft';
    IF n > 0 THEN
        RAISE EXCEPTION 'Down reddedildi: draft olmayan % kampanya var; geri alma onay verisini silerdi', n
            USING ERRCODE = 'restrict_violation';
    END IF;
END
$$;
-- +goose StatementEnd

DROP TRIGGER campaigns_approved_version_fixed ON campaigns;
DROP FUNCTION campaigns_keep_approved_version();

DROP TABLE messages;

ALTER TABLE campaigns
    DROP CONSTRAINT campaigns_completed_at_matches,
    DROP CONSTRAINT campaigns_approved_has_content,
    DROP CONSTRAINT campaigns_draft_has_no_approval,
    DROP CONSTRAINT campaigns_approved_content_fk,
    DROP COLUMN completed_at,
    DROP COLUMN approved_at,
    DROP COLUMN approved_content_version;

DROP TRIGGER campaign_contents_draft_only ON campaign_contents;
DROP TRIGGER campaign_contents_no_update ON campaign_contents;
DROP TABLE campaign_contents;

DROP FUNCTION campaign_contents_require_draft();
DROP FUNCTION campaign_contents_block_update();
DROP FUNCTION content_text_valid(text);
